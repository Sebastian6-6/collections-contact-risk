"""Repository map (``.context/MAP.md``): what lives in each folder.

Generated deterministically with the standard library, so building it
costs no model tokens. Partitioned files (``sales_20250101.csv``, ...)
collapse into one pattern line, CSV headers are sniffed from the first
bytes only, and unchanged files are served from a local cache.
"""

from __future__ import annotations

import csv
import io
import os
import re
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .fsutil import (
    atomic_write_text,
    human_size,
    read_json,
    read_text,
    stamp,
    write_json,
)
from .paths import Layout
from .topics import scope_base

DATA_EXT = {
    ".csv",
    ".tsv",
    ".parquet",
    ".json",
    ".jsonl",
    ".ndjson",
    ".xlsx",
    ".xls",
    ".feather",
    ".avro",
    ".orc",
}
HEADER = "# Repository map"
NOTE = (
    "<!-- generated by context-manager: do not edit. Folder purposes live "
    "in .context/map.json (set them with /c describe). -->"
)
_ROW = re.compile(r"^\|\s*`([^`]*)`\s*\|")
_DIGITS = re.compile(r"\d+")


@dataclass
class FileInfo:
    name: str
    size: int
    mtime: float
    rel: str


@dataclass
class Row:
    folder: str
    files: list[FileInfo] = field(default_factory=list)
    hidden_dirs: int = 0
    hidden_files: int = 0

    @property
    def depth(self) -> int:
        return 0 if not self.folder else self.folder.count("/") + 1


# -- scanning ---------------------------------------------------------------
def _pruned(names: list[str], skip: set[str]) -> list[str]:
    return sorted(n for n in names if not n.startswith(".") and n not in skip)


def _count_tree(path: Path, skip: set[str]) -> tuple[int, int]:
    dirs = files = 0
    for _, dirnames, filenames in os.walk(path):
        dirnames[:] = _pruned(dirnames, skip)
        dirs += len(dirnames)
        files += sum(1 for f in filenames if not f.startswith("."))
    return dirs, files


def scan(root: Path, skip: set[str], max_depth: int) -> list[Row]:
    rows: list[Row] = []
    for current, dirnames, filenames in os.walk(root):
        dirnames[:] = _pruned(dirnames, skip)
        rel = Path(current).relative_to(root).as_posix()
        rel = "" if rel == "." else rel
        row = Row(folder=rel)
        for name in sorted(f for f in filenames if not f.startswith(".")):
            path = Path(current) / name
            try:
                stat = path.stat()
            except OSError:
                continue
            row.files.append(
                FileInfo(
                    name,
                    stat.st_size,
                    stat.st_mtime,
                    f"{rel}/{name}" if rel else name,
                )
            )
        if row.depth >= max_depth and dirnames:
            for name in dirnames:
                sub_dirs, sub_files = _count_tree(Path(current) / name, skip)
                row.hidden_dirs += 1 + sub_dirs
                row.hidden_files += sub_files
            dirnames[:] = []
        if row.files or row.hidden_dirs:
            rows.append(row)
    return rows


# -- data file sniffing -----------------------------------------------------
def _csv_columns(path: Path) -> list[str] | None:
    try:
        with path.open("rb") as handle:
            sample = handle.read(65536)
    except OSError:
        return None
    for encoding in ("utf-8-sig", "cp1252"):
        try:
            text = sample.decode(encoding)
            break
        except UnicodeDecodeError:
            continue
    else:  # pragma: no cover - cp1252 decodes almost anything
        return None
    first = text.splitlines()[0] if text else ""
    if not first:
        return None
    try:
        dialect = csv.Sniffer().sniff(first, delimiters=",;\t|")
        delimiter = dialect.delimiter
    except csv.Error:
        delimiter = "\t" if path.suffix.lower() == ".tsv" else ","
    header = next(csv.reader(io.StringIO(first), delimiter=delimiter), [])
    header = [h.strip() for h in header]
    if not header or all(re.fullmatch(r"[-+\d.,]*", h) for h in header):
        return None  # no header row
    return header


def _parquet_info(path: Path) -> dict[str, Any] | None:
    try:
        import pyarrow.parquet as pq  # noqa: PLC0415 - optional dependency
    except ImportError:
        return None
    try:
        meta = pq.ParquetFile(path).metadata
        return {"rows": meta.num_rows, "cols": list(meta.schema.names)}
    except Exception:  # noqa: BLE001 - any unreadable file is just skipped
        return None


def _sniff(
    file: FileInfo, root: Path, cache: dict[str, Any]
) -> dict[str, Any]:
    cached = cache.get(file.rel)
    if (
        cached
        and cached.get("size") == file.size
        and cached.get("mtime") == file.mtime
    ):
        return cached.get("info", {})
    ext = Path(file.name).suffix.lower()
    info: dict[str, Any] = {}
    if ext in (".csv", ".tsv"):
        cols = _csv_columns(root / file.rel)
        if cols:
            info = {"cols": cols}
    elif ext == ".parquet":
        info = _parquet_info(root / file.rel) or {}
    cache[file.rel] = {"size": file.size, "mtime": file.mtime, "info": info}
    return info


# -- rendering --------------------------------------------------------------
def _cols(info: dict[str, Any]) -> str:
    cols = info.get("cols") or []
    if not cols:
        return ""
    shown = ", ".join(cols[:6]) + (", …" if len(cols) > 6 else "")
    return f"{len(cols)} cols: {shown}"


def _describe_data(
    files: list[FileInfo], root: Path, cache: dict[str, Any]
) -> list[str]:
    parts: list[str] = []
    groups: dict[tuple[str, str], list[FileInfo]] = defaultdict(list)
    for file in files:
        stem, ext = Path(file.name).stem, Path(file.name).suffix
        groups[(ext.lower(), _DIGITS.sub("*", stem))].append(file)

    singles: list[FileInfo] = []
    for (ext, pattern), members in groups.items():
        if len(members) >= 2 and "*" in pattern:
            members.sort(key=lambda f: f.name)
            digits = [_DIGITS.findall(Path(f.name).stem) for f in members]
            span = ""
            if digits[0] and digits[-1]:
                span = f" ({digits[0][-1]} → {digits[-1][-1]})"
            details = [
                f"{len(members)} × {ext.lstrip('.')}",
                human_size(sum(f.size for f in members)),
                f"`{pattern}{ext}`{span}",
            ]
            cols = _cols(_sniff(members[-1], root, cache))
            parts.append(" · ".join(details + ([cols] if cols else [])))
        else:
            singles.extend(members)

    if len(singles) > 4:
        by_ext = Counter(
            Path(f.name).suffix.lower().lstrip(".") for f in singles
        )
        total = human_size(sum(f.size for f in singles))
        parts.append(
            " · ".join(f"{n} × {e}" for e, n in sorted(by_ext.items()))
            + f" · {total}"
        )
    else:
        for file in sorted(singles, key=lambda f: f.name):
            info = _sniff(file, root, cache)
            details = [f"`{file.name}`", human_size(file.size)]
            if info.get("rows") is not None:
                details.append(f"{info['rows']:,} rows")
            cols = _cols(info)
            parts.append(" · ".join(details + ([cols] if cols else [])))
    return parts


def describe(row: Row, root: Path, cache: dict[str, Any]) -> str:
    data = [f for f in row.files if Path(f.name).suffix.lower() in DATA_EXT]
    other = [f for f in row.files if f not in data]
    parts = _describe_data(data, root, cache) if data else []
    if other:
        counts = Counter(
            Path(f.name).suffix.lower().lstrip(".") or "no-ext" for f in other
        )
        parts.append(" · ".join(f"{n} {e}" for e, n in counts.most_common()))
    if row.hidden_dirs:
        parts.append(
            f"+ {row.hidden_dirs} subfolders, {row.hidden_files} files"
        )
    return " · ".join(parts).replace("|", "\\|")


def build(layout: Layout, cfg: dict[str, Any]) -> dict[str, Any]:
    """Regenerate MAP.md. Returns stats and folders still lacking a purpose."""
    skip = set(cfg.get("skip_dirs", []))
    depth = max(1, int(cfg["map"].get("max_depth", 4)))
    max_rows = max(20, int(cfg["map"].get("max_rows", 200)))
    rows = scan(layout.root, skip, depth)
    while len(rows) > max_rows and depth > 1:
        depth -= 1
        rows = scan(layout.root, skip, depth)

    cache = read_json(layout.map_cache, default={}) or {}
    purposes = (read_json(layout.map_json, default={}) or {}).get(
        "folders", {}
    )
    total_files = sum(len(r.files) + r.hidden_files for r in rows)
    lines = [
        HEADER,
        NOTE,
        f"_Updated {stamp()} · {len(rows)} folders · {total_files:,} files · "
        f"depth ≤ {depth}_",
        "",
        "| Folder | Purpose | Contents |",
        "|---|---|---|",
    ]
    missing: list[str] = []
    for row in rows:
        purpose = purposes.get(row.folder, "")
        if not purpose and 0 < row.depth <= 2:
            missing.append(row.folder + "/")
        label = f"{row.folder}/" if row.folder else "./"
        cell = purpose.replace("|", "\\|") if purpose else "—"
        lines.append(
            f"| `{label}` | {cell} | {describe(row, layout.root, cache)} |"
        )

    alive = {f.rel for r in rows for f in r.files}
    write_json(
        layout.map_cache, {k: v for k, v in cache.items() if k in alive}
    )
    text = "\n".join(lines) + "\n"
    if read_text(layout.map_md).split("\n", 3)[3:] != text.split("\n", 3)[3:]:
        atomic_write_text(layout.map_md, text)
    return {
        "folders": len(rows),
        "files": total_files,
        "depth": depth,
        "missing": missing,
    }


def set_purpose(layout: Layout, folder: str, purpose: str) -> str:
    folder = folder.strip().replace("\\", "/").strip("/")
    folder = "" if folder in (".", "") else folder
    data = read_json(layout.map_json, default={}) or {}
    data.setdefault("folders", {})
    if purpose.strip():
        data["folders"][folder] = " ".join(purpose.split())
    else:
        data["folders"].pop(folder, None)
    write_json(layout.map_json, data)
    return folder


def rows_in_scope(layout: Layout, scope: list[str]) -> list[str]:
    """MAP.md table lines whose folder sits inside one of the scope entries."""
    if not scope:
        return []
    bases = {scope_base(entry) for entry in scope}
    result: list[str] = []
    for line in read_text(layout.map_md).splitlines():
        match = _ROW.match(line)
        if not match:
            continue
        folder = match.group(1)
        folder = "" if folder == "./" else folder
        if any(
            folder.startswith(b) or (b.startswith(folder) and folder)
            for b in bases
            if b
        ):
            result.append(line)
    return result

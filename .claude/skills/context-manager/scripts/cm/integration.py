"""Files the skill manages outside ``.context``.

``.gitignore`` block, the block in ``.claude/CLAUDE.md``, the ``/c`` alias
skill and the SessionStart hook in ``.claude/settings.json``. Each
``ensure_*`` function is idempotent and returns what it changed (pt-BR).
"""

from __future__ import annotations

import json
import shutil
from typing import Any

from . import blocks
from .config import rules_path
from .fsutil import atomic_write_text, read_raw, read_text
from .paths import SCRIPT_REL, SKILL_NAME, Layout
from .templates import render

ALIAS_MARK = "<!-- generated by context-manager: alias -->"
HOOK_MARK = f"{SKILL_NAME}/scripts/ctx.py"

GITIGNORE = {
    "complete": [".context/raw/", ".context/local/"],
    "minimal": [".context/raw/", ".context/converted/", ".context/local/"],
    "none": [".context/"],
    # Publishes originals and conversions; only machine-local state stays out.
    "full": [".context/local/"],
}

# Shown in the first-run plan (pt-BR).
GITIGNORE_LABEL = {
    "complete": "raw/ e local/ fora do git",
    "minimal": "raw/, converted/ e local/ fora do git",
    "none": ".context/ inteiro fora do git",
    "full": "só local/ fora do git; raw/ e converted/ publicados",
}


# -- .gitignore -------------------------------------------------------------
def ensure_gitignore(
    layout: Layout, cfg: dict[str, Any]
) -> tuple[list[str], bool]:
    """Returns ``(changes, opted_out)``. Created even without a git repo."""
    body = "\n".join(GITIGNORE[cfg["git_profile"]])
    text = read_raw(layout.gitignore)
    if blocks.has_block(text):
        if blocks.get_body(text) == body:
            return [], False
        atomic_write_text(
            layout.gitignore,
            blocks.upsert(text, body, blocks.HASH),
            newline="",
        )
        return [
            f".gitignore: bloco ajustado ao perfil '{cfg['git_profile']}'"
        ], False
    if cfg["applied"].get("gitignore"):
        return [], True  # removed on purpose after being applied: respect it
    atomic_write_text(
        layout.gitignore, blocks.upsert(text, body, blocks.HASH), newline=""
    )
    cfg["applied"]["gitignore"] = True
    return [".gitignore: bloco do context-manager adicionado"], False


# -- CLAUDE.md --------------------------------------------------------------
def claude_block(cfg: dict[str, Any]) -> str:
    """Rules injected into ``.claude/CLAUDE.md``; depends on the modules."""
    alias = cfg["alias"]
    lines_limit = cfg["large_file_threshold"]["lines"]
    mb_limit = cfg["large_file_threshold"]["bytes"] // 1_048_576
    rules_file = rules_path(cfg)
    rules = [
        f"Project rules live in `{rules_file}`"
        + (
            " (imported above)"
            if cfg["rules_file"] == "agents"
            else ", outside this block"
        )
        + "; `.context/PROJECT.md` is memory only (purpose, data sources, "
        "decision log). Write confirmed project-wide rules only there, "
        "never in PROJECT.md, and only with the user's consent. A rule that "
        "applies to one topic stays in that topic's STATE.md `## Decisions` "
        "(or a parent's `## Shared decisions`). Precedence: rules file > "
        "parent > topic; a narrower rule only refines, never contradicts.",
        f"Project memory lives in `.context/`. Resume a topic with "
        f"`/{alias} <topic>`; after a long block of work, suggest "
        f"`/{alias} save`.",
        "When resuming, load ONLY that topic's `STATE.md` plus "
        "`.context/PROJECT.md`, never every topic.",
        "Never edit `.context/raw/`. Shared files (`PROJECT.md`, "
        "`manifest.json`, `map.json`, `index.md`, `MAP.md`) change only "
        f"through `{SCRIPT_REL}`; an open topic's own `STATE.md` may be "
        "edited directly.",
    ]
    if cfg["modules"]["map"]:
        rules.append(
            "Check `.context/MAP.md` before opening data files. Files over "
            f"{lines_limit} lines or {mb_limit} MB: read a slice first "
            "(Read with a limit, `head`); read fully only when the task "
            "needs it."
        )
    if cfg["modules"]["ingest"]:
        rules.append(
            "Check `.context/index.md` before opening documents; read the "
            "converted Markdown in `.context/converted/` by page "
            "(`<!-- page N -->` markers), not the originals."
        )
    rules += [
        "Inside `.context/` use exact paths from the indexes: search tools "
        "may skip hidden or ignored folders.",
        "Never write credentials, tokens or connection strings into "
        "`.context/`.",
        "Never commit on your own; commits are the user's call.",
        f"Talk to the user in {cfg['language']['output']}; write memory "
        "files in English.",
    ]
    header = "## Context management (context-manager skill)"
    lines = [header, *(f"- {rule}" for rule in rules)]
    if cfg["rules_file"] == "agents":
        # A .claude/CLAUDE.md stops Claude Code from loading AGENTS.md on its
        # own, so the import is required; the path resolves from this file.
        lines = ["@../AGENTS.md", "", *lines]
    return "\n".join(lines)


def ensure_claude_block(layout: Layout, cfg: dict[str, Any]) -> list[str]:
    changes: list[str] = []
    root_text = read_raw(layout.root_claude_md)
    if blocks.has_block(root_text):
        cleaned = blocks.remove(root_text)
        if cleaned.strip():
            atomic_write_text(layout.root_claude_md, cleaned, newline="")
        else:
            layout.root_claude_md.unlink()
        changes.append("bloco duplicado removido do CLAUDE.md da raiz")
    body = claude_block(cfg)
    text = read_raw(layout.claude_md)
    if blocks.get_body(text) != body:
        atomic_write_text(
            layout.claude_md,
            blocks.upsert(text, body, blocks.HTML),
            newline="",
        )
        changes.append(
            ".claude/CLAUDE.md: bloco do context-manager "
            + ("atualizado" if blocks.has_block(text) else "adicionado")
        )
    return changes


# -- alias skill ------------------------------------------------------------
def ensure_alias(layout: Layout, alias: str) -> tuple[list[str], str | None]:
    """Return ``(changes, collision)``; never overwrite a user's skill."""
    changes: list[str] = []
    if layout.skills_dir.is_dir():
        for folder in layout.skills_dir.iterdir():
            skill = folder / "SKILL.md"
            if folder.name in (alias, SKILL_NAME) or not skill.is_file():
                continue
            if ALIAS_MARK in read_text(skill):
                shutil.rmtree(folder)
                changes.append(f"atalho antigo /{folder.name} removido")
    target = layout.alias_dir(alias) / "SKILL.md"
    current = read_text(target)
    if target.exists() and ALIAS_MARK not in current:
        return changes, (
            f"já existe uma skill sua chamada '{alias}'; o atalho "
            f"/{alias} não foi criado (troque 'alias' no config.json)"
        )
    expected = render("alias-skill.md", alias=alias)
    if current != expected:
        atomic_write_text(target, expected)
        changes.append(
            f"atalho /{alias} " + ("atualizado" if current else "criado")
        )
    return changes, None


# -- SessionStart hook ------------------------------------------------------
def hook_command() -> str:
    script = f'"$CLAUDE_PROJECT_DIR/{SCRIPT_REL}"'
    # Interpreter names differ per OS; on Windows "python3" may be the
    # Microsoft Store stub, which fails and falls through to the next one.
    return (
        f"python3 {script} hook 2>/dev/null || python {script} hook "
        f"2>/dev/null || py -3 {script} hook"
    )


def _is_ours(entry: Any) -> bool:
    return isinstance(entry, dict) and any(
        HOOK_MARK in str(h.get("command", ""))
        for h in entry.get("hooks", [])
        if isinstance(h, dict)
    )


def ensure_hook(layout: Layout, enabled: bool) -> tuple[list[str], str | None]:
    """Returns ``(changes, error)``; leaves every other hook untouched."""
    text = read_text(layout.settings)
    try:
        data = json.loads(text) if text.strip() else {}
    except json.JSONDecodeError:
        return [], ".claude/settings.json tem JSON inválido; hook não alterado"
    if not isinstance(data, dict):
        return (
            [],
            ".claude/settings.json não é um objeto JSON; hook não alterado",
        )

    hooks = data.get("hooks") if isinstance(data.get("hooks"), dict) else {}
    entries = [e for e in hooks.get("SessionStart", []) if not _is_ours(e)]
    had_ours = len(entries) != len(hooks.get("SessionStart", []))
    wanted = {
        "hooks": [
            {"type": "command", "command": hook_command(), "timeout": 15}
        ]
    }
    current_ours = [e for e in hooks.get("SessionStart", []) if _is_ours(e)]

    if enabled:
        if current_ours == [wanted]:
            return [], None
        entries.append(wanted)
        change = "hook de status " + (
            "atualizado" if had_ours else "adicionado"
        )
    else:
        if not had_ours:
            return [], None
        change = "hook de status removido (módulo desligado)"

    if entries:
        hooks["SessionStart"] = entries
    else:
        hooks.pop("SessionStart", None)
    if hooks:
        data["hooks"] = hooks
    else:
        data.pop("hooks", None)
    atomic_write_text(
        layout.settings, json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    )
    return [f".claude/settings.json: {change}"], None
